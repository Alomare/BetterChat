-- HD2-Addon: mods/alomare/better_chat
-- Better Chat by Alomare.
--
-- Quality of life for the game's text chat, each part set in Mod Options Menu (escape menu > MODS, optional):
-- - Sound alert: when another player's chat line arrives, one of the game's own UI sounds plays, at most once
--   every 2 seconds, chosen separately for the ship and for missions. Lines from players you muted don't count
--   (the game doesn't store those), nor do your own.
-- - Chat size: the chat box and its text scale by the size set.
-- - Paste: Ctrl+V adds the clipboard's text to the chat while you type.
-- - Inbound Language (Automatic by default; OFF turns it off): another player's line is sent to the translation
--   service by Windows' own curl.exe, started without a window; curl's options and the line go in through its
--   standard input (a config read with -K -), so its command line is always the same and holds no address, and the
--   reply comes back through a pipe read every frame: the game only waits for curl to start (a few ms). curl is
--   started once in advance, with nothing to do, as soon as translation is on. A line in another language than the
--   one chosen is added to the chat, on this machine only, through the game's own add-line, under the same sender.
-- - Outbound Language (OFF by default): when the player presses Enter in the chat, the mod takes the text
--   from the chat's field and empties it before the game sends it, has it translated, and sends the translation
--   through the game's own chat send (the original when translation fails or the text is already in that language).
-- - Translation Service: Google Translate's keyless endpoints (translate.googleapis.com), or an OpenAI-compatible
--   chat completions service the player sets in BetterChat_service.json (next to the Logs folder). Nothing is sent
--   anywhere while both translations are off.
--
-- How: the chat keeps its last 64 lines in a ring (first index, line count, then 64 lines of sender, time and
-- text). Every 200 ms the mod reads the ring's first index and count (one small read); when lines were added, it
-- reads their senders and compares them with the local player's peer id. The sound goes through the game's UI sound
-- function, the size through the game's widget scale setter on the chat widget.
-- Everything native is found in game.dll by code signatures (first at this build's addresses, else by a search of
-- its executable sections spread over frames, where a signature must match exactly once), and structure offsets
-- are read from the matched code. A feature whose code is missing stays off; without the chat ring the mod does
-- nothing. The mod never writes game memory.
