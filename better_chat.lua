local function read(address, size)
    local buf, got = ffi.new('uint8_t[?]', size), ffi.new('size_t[1]')
    if native.k32.better_chat_ReadProcessMemory(native.process, ffi.cast('const void *', address), buf, size, got) == 0
       or tonumber(got[0]) ~= size then
        return nil
    end
    return ffi.string(buf, size)
end

local function u32(blob, offset)
    offset = offset or 0
    if not blob or #blob < offset + 4 then return nil end
    local v = ffi.new('uint32_t[1]')
    ffi.copy(v, blob:sub(offset + 1, offset + 4), 4)
    return tonumber(v[0])
end

local function read32(address) return u32(read(address, 4)) end

local function pointer(blob)
    if not blob or #blob ~= 8 then return nil end
    local v = ffi.new('uint64_t[1]')
    ffi.copy(v, blob, 8)
    local a = tonumber(v[0])
    if a < 0x10000 or a >= 0x800000000000 then return nil end
    return a
end

local function hex(blob)
    if not blob then return 'unreadable' end
    return (blob:reverse():gsub('.', function(c) return string.format('%02x', c:byte()) end))
end

-- Two floats from their 8 bytes.
local function vec_values(blob)
    if not blob or #blob ~= 8 then return nil end
    local v = ffi.new('float[2]')
    ffi.copy(v, blob, 8)
    return tonumber(v[0]), tonumber(v[1])
end

