-- New chat lines

local ring = {ctx = nil, first = 0, count = 0}
local clock, last_sound, last_check = 0, -math.huge, -math.huge

local function alert(others, mine, total)
    note(string.format('%d new chat line(s), %d from other players, %d from you', total, others, mine))
    -- The ship's choice everywhere but in missions.
    local choice = game_mode() == MODE_MISSION and options.alert_mission or options.alert_ship
    if others == 0 or not options.alert then return end
    if clock - last_sound >= COOLDOWN then
        if play(choice, 'new message') then last_sound = clock end
    else
        note('Sound skipped (cooldown)')
    end
end

-- The chat line flags the game keeps per line, after the sender and text (diagnostics): friend, shown, filtered,
-- and two display bytes.
local LINE_FLAGS = 0x209       -- from the sender (0xda1 - 0xb98 in this build)
local function line_flags(chat, slot)
    local b = read(chat + V.line_sender + LINE_FLAGS + slot * V.line_stride, 5)
    if not b then return '?' end
    return string.format('%d%d%d%d%d', b:byte(1, 5))
end

local function watch_chat()
    local ctx = pointer(read(native.base + V.context, 8))
    if not ctx then
        if ring.ctx then note('Network context gone'); ring.ctx = nil end
        return
    end
    local chat = ctx + V.chat
    local header = read(chat + V.ring_first, 8)
    local first, count = u32(header, 0), u32(header, 4)
    if not first or first >= RING_SIZE or count > RING_SIZE then return end
    if ring.ctx ~= ctx or count < ring.count then
        -- A new session or a cleared history: lines already there are not new.
        note(string.format('Chat history: context 0x%x, first %d, count %d', ctx, first, count))
        ring.ctx, ring.first, ring.count = ctx, first, count
        return
    end
    local new = (count - ring.count) + (first - ring.first) % RING_SIZE
    ring.first, ring.count = first, count
    if new <= 0 then return end
    new = math.min(new, RING_SIZE)
    local own = read(ctx + V.local_peer, 8)
    local others, mine = 0, 0
    for k = new, 1, -1 do
        local slot = (first + count - k) % RING_SIZE
        local sender = read(chat + V.line_sender + slot * V.line_stride, 8)
        local text = read(chat + V.line_text + slot * V.line_stride, 0x200)
        local length = text and (text:find('\0', 1, true) or 0x201) - 1 or -1
        local from_other = sender ~= nil and own ~= nil and sender ~= own
        if from_other then others = others + 1 elseif sender ~= nil and sender == own then mine = mine + 1 end
        note(string.format('Line %d: sender %s%s, %d bytes, flags %s', slot, hex(sender),
                           from_other and '' or ' (you)', length, line_flags(chat, slot)))
        if sender and length > 0 and (from_other or options.translate_own) then enqueue(sender, text:sub(1, length)) end
        -- Your own line holding a message the mod took from the field: the game sent it itself (it ran first), so
        -- the mod sends nothing more for it.
        if sender and own and sender == own and length > 0 then
            local line = text:sub(1, length)
            for id, pending in pairs(outbound.pending) do
                if not pending.sent_by_game and pending.text == line then
                    pending.sent_by_game = true
                    outbound.game_first = outbound.game_first + 1
                    note(string.format('Outbound %d: the game sent the message itself (game first %d times)', id,
                                       outbound.game_first))
                    break
                end
            end
        end
    end
    alert(others, mine, new)
end

local function ring_header(ctx)
    local header = read(ctx + V.chat + V.ring_first, 8)
    return u32(header, 0), u32(header, 4)
end

-- Adds the finished translations to the chat through the game's add-line (on this machine only) and sends the
-- outbound messages through the chat's own send (to every player, and to this chat), right after a check of the
-- chat; then takes the history as it is now: those lines are not new messages.
local function deliver()
    watch_chat()
    local ctx = ring.ctx
    local same_chat = ctx and pointer(read(native.base + V.context, 8)) == ctx
    for _, entry in ipairs(translate.show) do
        if same_chat then
            local sender = ffi.new('uint64_t[1]')
            ffi.copy(sender, entry.sender, 8)
            fn.add_line(ctx + V.chat, sender[0], entry.text)
            note('Translation ' .. entry.id .. ' shown')
        else
            note('Translation ' .. entry.id .. ' not shown: the chat changed')
        end
    end
    translate.show = {}
    for _, entry in ipairs(translate.send) do
        if same_chat then
            if not outbound.called then
                outbound.called = true
                note('Outbound: first call of the chat send')  -- a crash right after this line names the call
            end
            local f0, c0 = ring_header(ctx)
            fn.send(ctx + V.chat, 0, entry.text)
            local f1, c1 = ring_header(ctx)
            local reached = f1 ~= f0 or c1 ~= c0
            note(string.format('Outbound %d sent %s (%d bytes%s)%s', entry.id,
                               entry.translated and 'translated' or 'as written', #entry.text,
                               entry.why and (', ' .. entry.why) or '', reached and '' or ': not in the chat'))
            -- A translation the game didn't take goes as written.
            if not reached and entry.translated then
                fn.send(ctx + V.chat, 0, entry.original)
                local f2, c2 = ring_header(ctx)
                note(string.format('Outbound %d sent as written instead%s', entry.id,
                                   (f2 ~= f1 or c2 ~= c1) and '' or ': not in the chat either'))
            end
        else
            note('Outbound ' .. entry.id .. ' not sent: the chat changed')
        end
    end
    translate.send = {}
    if not ctx then return end
    local header = read(ctx + V.chat + V.ring_first, 8)
    local first, count = u32(header, 0), u32(header, 4)
    if first and first < RING_SIZE and count <= RING_SIZE then ring.first, ring.count = first, count end
end

