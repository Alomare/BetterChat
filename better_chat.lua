local function service_path()
    local logs = type(loader) == 'table' and loader.log_directory
    if type(logs) == 'string' and logs ~= '' then
        local parent = (logs:gsub('[/\\]+$', '')):match('^(.*)[/\\][^/\\]+$')
        if parent and parent ~= '' then return parent .. '\\' .. SERVICE_FILE end
    end
    local ok, appdata = pcall(os.getenv, 'LOCALAPPDATA')
    if ok and type(appdata) == 'string' and appdata ~= '' then
        return appdata .. '\\CowboyBingus\\Helldivers2\\' .. SERVICE_FILE
    end
end

-- Why an address can't be used, or nil: https, or http to this PC only (a model running locally).
local function service_url_why(url)
    if url == '' then return 'base_url is empty' end
    if url:find('[%s%c"\\]') then return 'base_url has spaces, quotes or backslashes' end
    if url:match('^https://[^/]+') then return nil end
    local host = url:match('^http://(%[[^%]]+%])') or url:match('^http://([^/:]+)')
    if host == 'localhost' or host == '127.0.0.1' or host == '[::1]' then return nil end
    return 'base_url must start with https:// (http:// only for localhost)'
end

-- Takes the file's settings, or returns why they can't be used.
local function parse_service(body)
    if not body then return 'the file is unreadable' end
    if #body > SERVICE_FILE_MAX then return 'the file is too big' end
    local ok, data = pcall(json_value, body)
    if not ok or type(data) ~= 'table' then return 'the file is not valid JSON' end
    local function text_of(k) return type(data[k]) == 'string' and data[k]:match('^%s*(.-)%s*$') or '' end
    local url = (text_of('base_url'):gsub('/+$', ''))
    local key, model, prompt = text_of('api_key'), text_of('model'), text_of('prompt')
    local why = service_url_why(url)
    if why then return why end
    if model == '' then return 'model is empty' end
    if key:find('[%c"\\]') then return 'api_key has quotes, backslashes or control characters' end
    if #prompt > PROMPT_MAX then return 'prompt is longer than ' .. PROMPT_MAX .. ' bytes' end
    if prompt ~= '' and not prompt:find('{language}', 1, true) then return 'prompt has no {language}' end
    local glossary = {}
    if data.glossary ~= nil then
        if type(data.glossary) ~= 'table' then return 'glossary is not an object' end
        for term, form in pairs(data.glossary) do
            if type(term) ~= 'string' or type(form) ~= 'string' or #term < 2 or #term > 64 or #form > 64 then
                return 'a glossary entry is not a short text'
            end
            glossary[#glossary + 1] = {term = term, form = form}
            if #glossary > GLOSSARY_MAX then return 'more than ' .. GLOSSARY_MAX .. ' glossary entries' end
        end
        table.sort(glossary, function(a, b) return a.term < b.term end)
    end
    service.url, service.key, service.model = url, key, model
    service.prompt, service.glossary = prompt ~= '' and prompt or DEFAULT_PROMPT, glossary
end

-- Reads the service's file (writing the template when there is none). True when the service can be used.
load_service = function()
    service.ready = false
    service.path = service.path or service_path()
    local why
    if not service.path then
        why = 'the Logs folder is unknown'
    elseif type(io) ~= 'table' or type(io.open) ~= 'function' then
        why = 'files cannot be read'
    else
        local f = io.open(service.path, 'rb')
        if f then
            local ok, body = pcall(function() local s = f:read(SERVICE_FILE_MAX + 1); f:close(); return s end)
            why = parse_service(ok and body or nil)
        else
            local out = io.open(service.path, 'wb')
            local written = out and pcall(function() out:write(SERVICE_TEMPLATE); out:close() end)
            why = written and SERVICE_FILE .. ' was missing: a template was written next to the Logs folder; fill in '
                              .. 'base_url, api_key and model'
                          or ('cannot create ' .. SERVICE_FILE)
        end
    end
    service.why, service.ready = why, not why
    local said = why and ('off: ' .. why)
                 or string.format('ready: %s, model %s%s', service.url:match('^https?://([^/]+)'), service.model,
                                  service.key == '' and ', no key' or '')
    if said ~= service.said then
        service.said = said
        note('Custom service ' .. said)
    end
    return service.ready
end

-- A text as a JSON string: quotes and backslashes escaped, control characters as \u escapes.
local function json_text(s)
    return '"' .. s:gsub('[%c"\\]', function(c)
        if c == '"' then return '\\"' elseif c == '\\' then return '\\\\' end
        return string.format('\\u%04x', c:byte())
    end) .. '"'
end

-- The translation and the message's language from an OpenAI-compatible reply ({"choices": [{"message": {"content":
-- "[es] ..."}}]}). A model's reasoning in <think> tags and quotes around the translation are left out; a reply
-- without the language in brackets is still a translation (of an unknown language).
local function parse_custom_reply(body)
    local ok, data = pcall(json_value, body)
    if not ok or type(data) ~= 'table' then return nil, 'bad reply' end
    local choice = type(data.choices) == 'table' and data.choices[1]
    local content = type(choice) == 'table' and type(choice.message) == 'table' and choice.message.content
    if type(content) ~= 'string' then return nil, 'no translation in the reply' end
    content = content:gsub('<think>.-</think>', ''):gsub('%c', ' ')
    local source, text = content:match('^%s*%[%s*(%a%a%a?[%-_]?%a*)%s*%]%s*(.-)%s*$')
    if not source then text = content:match('^%s*(.-)%s*$') end
    text = text:match('^"(.+)"$') or text
    if text == '' then return nil, 'empty translation' end
    return text, source and (source:lower():gsub('_', '-')) or nil
end

-- The error type an OpenAI-compatible service gives with an HTTP error ({"error": {"type": ..., "code": ...}}), as a
-- short word; never its message, which may quote the line.
local function api_error(body)
    local ok, data = pcall(json_value, body)
    local e = ok and type(data) == 'table' and data.error
    local kind = type(e) == 'table' and (type(e.type) == 'string' and e.type or type(e.code) == 'string' and e.code)
    return kind and (kind:gsub('[^%w_%.%-]', '')):sub(1, 40) or nil
end

-- The first bytes of a UTF-8 text, never splitting a character.
local function utf8_cut(s, max)
    if #s <= max then return s end
    local cut = max
    while cut > 0 and s:byte(cut + 1) >= 0x80 and s:byte(cut + 1) < 0xc0 do cut = cut - 1 end
    return s:sub(1, cut)
end

-- The first `chars` characters of a UTF-8 text, within `bytes` bytes.
local function utf8_head(s, chars, bytes)
    local at, n = 1, 0
    while at <= #s and n < chars do
        local b = s:byte(at)
        local size = b < 0x80 and 1 or b < 0xe0 and 2 or b < 0xf0 and 3 or 4
        if at + size - 1 > bytes then break end
        at, n = at + size, n + 1
    end
    return s:sub(1, at - 1)
end

local function quoted(s) return '"' .. s:gsub('[%c]', ' ') .. '"' end

-- An ASCII text as a NUL-terminated UTF-16 buffer.
local function wide(s)
    local buf = ffi.new('uint16_t[?]', #s + 1)
    for i = 1, #s do buf[i - 1] = s:byte(i) end
    return buf
end

local counter = ffi.new('int64_t[1]')
local function now()  -- seconds, from the performance counter
    native.k32.better_chat_QueryPerformanceCounter(counter)
    return tonumber(counter[0]) / perf.freq
end

-- The performance counter, for every timing: false when Windows has none.
local function init_clock()
    local freq = ffi.new('int64_t[1]')
    if native.k32.better_chat_QueryPerformanceFrequency(freq) == 0 or tonumber(freq[0]) <= 0 then return false end
    perf.freq, perf.now = tonumber(freq[0]), now
    return true
end

local function close(handle)
    if handle ~= nil then native.k32.better_chat_CloseHandle(handle) end
end

-- Finds Windows' curl.exe (System32; Windows 10 1803 and later). True, or false and the reason.
local function find_curl()
    local k = native.k32
    if not perf.freq then return false, 'no performance counter' end
    local buf = ffi.new('uint16_t[260]')
    local n = k.better_chat_GetSystemDirectoryW(buf, 260)
    if n == 0 or n >= 260 then return false, 'system folder unreadable' end
    local chars = {}
    for i = 0, n - 1 do
        if buf[i] >= 0x80 then return false, 'system folder name is not ASCII' end
        chars[#chars + 1] = string.char(buf[i])
    end
    local dir = table.concat(chars)
    local path = dir .. '\\curl.exe'
    local attributes = k.better_chat_GetFileAttributesW(wide(path))
    if attributes == 0xffffffff or math.floor(attributes / 16) % 2 == 1 then
        return false, 'curl.exe not found in ' .. dir
    end
    translate.curl, translate.dir = path, dir
    return true
end

-- A value in curl's config, quoted, with backslashes and quotes escaped and control characters as spaces: a chat
-- line can't end the value or the config line, so it can't add an option.
local function config_value(s)
    return '"' .. s:gsub('%c', ' '):gsub('[\\"]', '\\%0') .. '"'
end

-- Whether a lower-cased line mentions a lower-cased term: anywhere for a term in another script, else as a whole word
-- (or its English plural).
local function mentions(lower, term)
    if term:find('[\128-\255]') then return lower:find(term, 1, true) ~= nil end
    local from = 1
    while true do
        local s, e = lower:find(term, from, true)
        if not s then return false end
        local rest = lower:sub(e + 1, e + 3)
        if not lower:sub(s - 1, s - 1):find('%w') and (not rest:find('^%w') or rest:find('^e?s%f[%W]')) then
            return true
        end
        from = s + 1
    end
end

-- The game terms a line mentions, as {from, to}: into Chinese the English names, into English the Chinese ones; the
-- longest first, a term inside a longer one left out ("Devastator" in "Heavy Devastator"), the player's own terms
-- (`taken`, lower-cased) left out.
local function game_terms(lower, target, taken)
    local column = (target == 'zh-CN' and 2) or (target == 'zh-TW' and 3) or nil
    local found = {}
    for _, t in ipairs(GAME_TERMS) do
        local from
        if column then
            from = mentions(lower, t[1]:lower()) and t[1]
        elseif target == 'en' then
            from = (mentions(lower, t[2]) and t[2]) or (mentions(lower, t[3]) and t[3])
        end
        local to = column and t[column] or t[1]
        if from and from ~= to and not taken[from:lower()] then found[#found + 1] = {from = from, to = to} end
    end
    table.sort(found, function(a, b) return #a.from > #b.from or (#a.from == #b.from and a.from < b.from) end)
    local kept = {}
    for _, f in ipairs(found) do
        local inside = false
        for _, k in ipairs(kept) do
            if k.from:lower():find(f.from:lower(), 1, true) then inside = true; break end
        end
        if not inside and #kept < GAME_TERM_HINTS then kept[#kept + 1] = f end
    end
    return kept
end

-- curl's config for a line to the custom service: a POST to <base_url>/chat/completions with the prompt (and the
-- glossary and game terms the line mentions) as the system message and the line as the user message. No temperature
-- or token limit is set: some models accept only their defaults.
local function custom_config(entry)
    local language = LANGUAGE_NAMES[entry.target] or entry.target
    local system = service.prompt:gsub('{language}', function() return language end)
    local hints, lower, taken = {}, entry.text:lower(), {}
    for _, g in ipairs(service.glossary) do
        if mentions(lower, g.term:lower()) then
            hints[#hints + 1] = g.term .. ' = ' .. g.form
            taken[g.term:lower()] = true
        end
    end
    for _, t in ipairs(game_terms(lower, entry.target, taken)) do hints[#hints + 1] = t.from .. ' = ' .. t.to end
    if #hints > 0 then system = system .. '\nWrite these terms like this: ' .. table.concat(hints, '; ') .. '.' end
    local body = '{"model":' .. json_text(service.model) .. ',"messages":[{"role":"system","content":'
                 .. json_text(system) .. '},{"role":"user","content":' .. json_text(entry.text) .. '}]}'
    local lines = {'silent', 'show-error', 'max-time = ' .. CUSTOM_TIMEOUT, 'max-filesize = ' .. REPLY_MAX,
                   'header = ' .. config_value('Content-Type: application/json')}
    if service.key ~= '' then lines[#lines + 1] = 'header = ' .. config_value('Authorization: Bearer ' .. service.key) end
    lines[#lines + 1] = 'data-raw = ' .. config_value(body)                -- the body as written (no @file)
    lines[#lines + 1] = 'write-out = "\\n@@ %{http_code}"'
    lines[#lines + 1] = 'url = ' .. config_value(service.url .. '/chat/completions')
    lines[#lines + 1] = ''
    return table.concat(lines, '\n')
end

-- curl's config for a line: the request (the line in it) and how the reply is written.
local function curl_config(entry)
    if entry.service == 'custom' then return custom_config(entry) end
    entry.endpoint = translate.google
    return table.concat({
        'silent', 'show-error',                                         -- errors only
        'max-time = ' .. CURL_TIMEOUT, 'max-filesize = ' .. REPLY_MAX,
        'get', 'data-urlencode = ' .. config_value('q=' .. entry.text),  -- the line, in the address's query
        'write-out = "\\n@@ %{http_code}"',                             -- the HTTP status after the body
        'url = ' .. config_value(GOOGLE[entry.endpoint].url .. entry.target), ''}, '\n')
end

-- Starts curl for one line (or, for the warm-up, with an empty config: it exits at once, "no URL", code 2): true, or
-- nil and the reason. The command line is always the same, `curl.exe -K -`: the first start of a curl with an address
-- on its command line took 266 and 311 ms on the game's thread in game (something inspects it), then 5 ms for the
-- same command line; a curl -V took 9 ms (5-recon-3).
local function spawn(entry)
    local config = entry.warmup and '' or curl_config(entry)
    if #config > CONFIG_MAX then return nil, 'line too long' end
    local k = native.k32
    local sa = ffi.new('BetterChatSA')
    sa.nLength, sa.bInheritHandle = ffi.sizeof(sa), 1
    local in_r, in_w, out_r, out_w = ffi.new('void *[1]'), ffi.new('void *[1]'), ffi.new('void *[1]'),
                                     ffi.new('void *[1]')
    if k.better_chat_CreatePipe(in_r, in_w, sa, IN_PIPE) == 0 then return nil, 'CreatePipe failed' end
    if k.better_chat_CreatePipe(out_r, out_w, sa, 0x10000) == 0 then
        close(in_r[0]); close(in_w[0])
        return nil, 'CreatePipe failed'
    end
    -- This process's ends are not inherited; curl gets only its own two ends (a handle list, when available).
    k.better_chat_SetHandleInformation(in_w[0], 1, 0)
    k.better_chat_SetHandleInformation(out_r[0], 1, 0)
    local si = ffi.new('BetterChatStartupInfoEx')
    si.StartupInfo.cb = ffi.sizeof(si)
    si.StartupInfo.dwFlags = 0x100  -- STARTF_USESTDHANDLES
    si.StartupInfo.hStdInput, si.StartupInfo.hStdOutput, si.StartupInfo.hStdError = in_r[0], out_w[0], out_w[0]
    local flags = 0x08000000  -- CREATE_NO_WINDOW
    local size = ffi.new('size_t[1]')
    k.better_chat_InitializeProcThreadAttributeList(nil, 1, 0, size)
    local list = tonumber(size[0]) > 0 and ffi.new('uint8_t[?]', tonumber(size[0]))
    local handles = ffi.new('void *[2]', in_r[0], out_w[0])
    if list and k.better_chat_InitializeProcThreadAttributeList(list, 1, 0, size) ~= 0 then
        if k.better_chat_UpdateProcThreadAttribute(list, 0, 0x20002, handles, ffi.sizeof(handles), nil, nil) ~= 0 then
            si.lpAttributeList, flags = list, flags + 0x80000  -- PROC_THREAD_ATTRIBUTE_HANDLE_LIST, EXTENDED_STARTUPINFO
        else
            k.better_chat_DeleteProcThreadAttributeList(list)
            list = nil
        end
    else
        list = nil
    end
    local command = '"' .. translate.curl .. '" -K -'
    local info = ffi.new('BetterChatProcessInfo')
    local t0 = now()
    local ok = k.better_chat_CreateProcessW(wide(translate.curl), wide(command), nil, nil, 1, flags, nil,
                                            wide(translate.dir), si, info)
    local spawn_ms = (now() - t0) * 1000
    perf.spawn = perf.spawn + spawn_ms
    local err = ok == 0 and k.better_chat_GetLastError() or 0
    if list then k.better_chat_DeleteProcThreadAttributeList(list) end
    close(in_r[0]); close(out_w[0])
    if ok == 0 then
        close(in_w[0]); close(out_r[0])
        return nil, 'CreateProcess failed (error ' .. tostring(err) .. ')'
    end
    close(info.hThread)
    if #config > 0 then
        local done = ffi.new('uint32_t[1]')
        k.better_chat_WriteFile(in_w[0], config, #config, done, nil)  -- fits the pipe: never waits
    end
    close(in_w[0])
    translate.job = {entry = entry, process = info.hProcess, out = out_r[0], started = t0, spawn_ms = spawn_ms,
                     chunks = {}, size = 0}
    return true
end

-- Reads what curl wrote so far; 'done' once it exited (everything read), 'timeout' when it was ended.
local function poll(job)
    local k = native.k32
    local exited = k.better_chat_WaitForSingleObject(job.process, 0) == 0
    local available, got = ffi.new('uint32_t[1]'), ffi.new('uint32_t[1]')
    while job.size < REPLY_MAX and k.better_chat_PeekNamedPipe(job.out, nil, 0, nil, available, nil) ~= 0
          and available[0] > 0 do
        local n = math.min(tonumber(available[0]), REPLY_MAX - job.size)
        local buf = ffi.new('uint8_t[?]', n)
        if k.better_chat_ReadFile(job.out, buf, n, got, nil) == 0 or got[0] == 0 then break end
        job.chunks[#job.chunks + 1] = ffi.string(buf, got[0])
        job.size = job.size + got[0]
    end
    if exited then return 'done' end
    if now() - job.started > (job.entry.limit or JOB_LIMIT) then
        k.better_chat_TerminateProcess(job.process, 1)
        return 'timeout'
    end
end

-- An outbound message's result: the translation, or nil to send it as written (`why`: translation failed, already
-- in the language...). Queued for the next delivery, cut to the chat's own character limit, unless the game sent the
-- message itself meanwhile.
local function outbound_result(entry, translation, why)
    local pending = outbound.pending[entry.id]
    outbound.pending[entry.id] = nil
    if not pending then return end
    if pending.sent_by_game then
        note('Outbound ' .. entry.id .. ' not sent: the game sent the message itself')
        return
    end
    local text = (translation or entry.text):gsub('%c', ' ')
    text = utf8_head(text, pending.chars or 0x200, 0x1ff)
    translate.send[#translate.send + 1] = {id = entry.id, text = text, translated = translation ~= nil, why = why,
                                           original = entry.text}
end

local function finish(job, how)
    local entry = job.entry
    local exit_code = ffi.new('uint32_t[1]')
    native.k32.better_chat_GetExitCodeProcess(job.process, exit_code)
    close(job.process); close(job.out)
    translate.job = nil
    local ms = (now() - job.started) * 1000
    if entry.warmup then
        note(string.format('Curl warm-up (%.0f ms, start %.1f ms): %s, exit %d', ms, job.spawn_ms, how, exit_code[0]))
        return
    end
    local out = table.concat(job.chunks)
    local at, _, status = out:find('\n@@ (%d+)%s*$')
    local body = at and out:sub(1, at - 1) or out
    local head = string.format('%s %d (%.0f ms, start %.1f ms)', entry.kind == 'outbound' and 'Outbound' or 'Translation',
                               entry.id, ms, job.spawn_ms)
    if how == 'timeout' or exit_code[0] ~= 0 or status ~= '200' then
        -- curl's own error message, or the custom service's error type (never the reply, which can hold the line).
        local api = entry.service == 'custom' and exit_code[0] == 0 and api_error(body)
        note(string.format('%s failed: %s, curl exit %d, HTTP %s%s%s', head, how, exit_code[0], tostring(status),
                           exit_code[0] ~= 0 and (': ' .. quoted(body:sub(1, 120))) or '', api and (', ' .. api) or ''))
        -- Google refused the endpoint (429 "automated queries", 403): the other one, for this line (at once) and the
        -- next ones. A line goes to each endpoint at most once.
        if entry.service == 'google' and exit_code[0] == 0 and (status == '429' or status == '403')
           and not entry.switched then
            if entry.endpoint == translate.google then
                translate.google = translate.google % #GOOGLE + 1
                note(string.format('Google endpoint %s refused (HTTP %s): now %s', GOOGLE[entry.endpoint].name, status,
                                   GOOGLE[translate.google].name))
            end
            if entry.endpoint ~= translate.google and (entry.kind == 'outbound' or options.translate) then
                entry.switched, entry.not_before = true, nil
                table.insert(translate.queue, 1, entry)
                return
            end
        end
        -- A server error or a network failure is tried once more, a second later (an outbound message is not: the
        -- player is waiting, so it goes as written).
        local transient = how ~= 'timeout' and (exit_code[0] ~= 0 or (status or ''):match('^5'))
        if entry.kind == 'outbound' then
            outbound_result(entry, nil, 'translation failed')
        elseif transient and not entry.retried and options.translate then
            entry.retried, entry.not_before = true, now() + RETRY_DELAY
            table.insert(translate.queue, 1, entry)
            note('Translation ' .. entry.id .. ' will be retried')
        end
        return
    end
    local text, source
    if entry.service == 'custom' then text, source = parse_custom_reply(body) else text, source = parse_reply(body) end
    if not text then
        note(string.format('%s failed: %s', head, source))
        if entry.kind == 'outbound' then outbound_result(entry, nil, 'translation failed') end
        return
    end
    note(string.format('%s %s -> %s', head, source or '?', entry.target))
    local same = (source and same_language(source, entry.target) and ('already in ' .. entry.target))
                 or (text:lower() == entry.text:lower() and 'same as the line') or nil
    if entry.kind == 'outbound' then
        outbound_result(entry, not same and text or nil, same)
    elseif same then
        note('Translation ' .. entry.id .. ' not shown: ' .. same)
    elseif features.show ~= true then
        note('Translation ' .. entry.id .. ' not shown: ' .. tostring(features.show))
    else
        local label = source and ('[' .. (source:match('^%a+') or source):upper() .. '] ') or ''
        translate.show[#translate.show + 1] = {id = entry.id, sender = entry.sender,
                                               text = utf8_cut(label .. text:gsub('%c', ' '), SHOW_MAX)}
    end
end

-- An ASCII-only line with fewer than MIN_LETTERS letters is not translated (misdetected: "gg", "ez", "o7").
local function too_short(text)
    return not text:find('[\128-\255]') and select(2, text:gsub('%a', '')) < MIN_LETTERS
end

-- The service a new line goes to, or nil and why none can take it.
local function current_service()
    local id = SERVICES[options.service].id
    if id == 'custom' and not service.ready then return nil, 'custom service ' .. service.why end
    return id
end

local function new_entry(kind, text, target)
    local id, why = current_service()
    if not id then return nil, why end
    translate.serial = translate.serial + 1
    return {id = translate.serial, kind = kind, text = text, target = target, service = id,
            limit = id == 'custom' and CUSTOM_JOB_LIMIT or JOB_LIMIT}
end

-- A chat line to translate (sender: its 8 bytes as read). The oldest inbound line goes when QUEUE_MAX wait.
local function enqueue(sender, text)
    if not options.translate or features.translate ~= true or text == '' then return end
    if too_short(text) then
        note('Line not translated: too short')
        return
    end
    local entry, why = new_entry('inbound', text, target_language())
    if not entry then
        note('Line not translated: ' .. why)
        return
    end
    entry.sender = sender
    local waiting, oldest = 0, nil
    for i, e in ipairs(translate.queue) do
        if e.kind == 'inbound' then waiting, oldest = waiting + 1, oldest or i end
    end
    if waiting >= QUEUE_MAX then
        note('Translation ' .. translate.queue[oldest].id .. ' dropped (queue full)')
        table.remove(translate.queue, oldest)
    end
    translate.queue[#translate.queue + 1] = entry
end

-- A message taken from the chat's field: ahead of every inbound line (the player is waiting for it). The service
-- was checked by the caller.
local function enqueue_outbound(text, chars)
    local entry = new_entry('outbound', text, outbound_language())
    local at = 1
    while translate.queue[at] and translate.queue[at].kind == 'outbound' do at = at + 1 end
    table.insert(translate.queue, at, entry)
    outbound.pending[entry.id] = {text = text, chars = chars}
    return entry
end

-- Sends the waiting outbound messages as written (Translate Outbound turned off, or translation turned off), in order.
flush_outbound = function(why)
    local keep, flushed = {}, {}
    for _, e in ipairs(translate.queue) do
        if e.kind == 'outbound' then flushed[#flushed + 1] = e else keep[#keep + 1] = e end
    end
    translate.queue = keep
    for _, e in ipairs(flushed) do outbound_result(e, nil, why) end
end

-- One step per frame: reads the running curl, else starts the next line.
local function pump()
    if translate.job then
        local how = poll(translate.job)
        if how then finish(translate.job, how) end
        return
    end
    if not options.translate then
        -- Inbound lines are dropped; outbound messages stay (they go as written when Translate Outbound is off).
        local keep = {}
        for _, e in ipairs(translate.queue) do if e.kind == 'outbound' then keep[#keep + 1] = e end end
        if #keep ~= #translate.queue then translate.queue = keep end
    end
    if not (options.translate or options.outbound or #translate.queue > 0) then return end
    -- curl's first start in a session may be slow (see spawn): it is done once, as soon as translation is on (while
    -- the game loads, or in the menu where it was turned on), with a curl that sends nothing, so that no chat line
    -- waits for it.
    if not translate.warm then
        translate.warm = true
        local ok, why = spawn({warmup = true, text = ''})
        if not ok then note('Curl warm-up not started: ' .. why) end
        return
    end
    local entry = translate.queue[1]
    if not entry or (entry.not_before and now() < entry.not_before) then return end
    table.remove(translate.queue, 1)
    local ok, why = spawn(entry)
    if not ok then
        note((entry.kind == 'outbound' and 'Outbound ' or 'Translation ') .. entry.id .. ' not started: ' .. why)
        if entry.kind == 'outbound' then outbound_result(entry, nil, 'not started') end
    end
end

