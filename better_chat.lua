-- Mod Options Menu v1.1+ (version 2) takes texts as functions and calls them when its pages open, so the texts
-- follow the game's language; v1.0 takes strings with limits, where a translation that does not fit stays English.
-- One function per key, so repeated registrations agree.
local text_functions = {}
local function host_text(host, functions_from, key, limit)
    if (tonumber(host.version) or 1) >= functions_from then
        local fn = text_functions[key]
        if not fn then fn = function() return tr(key) end; text_functions[key] = fn end
        return fn
    end
    local value = tr(key)
    return #value <= limit and value or tr.english[key]
end

