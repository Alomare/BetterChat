-- Resolution: signatures -> values and the game's functions

local code = nil  -- the signature engine
local V = {}      -- values read from the matched code (offsets; globals and functions as rvas)
local fn = {}     -- the game's functions that were found
local features = {}  -- feature -> true, or the reason it is off

local function need(names, values)
    for _, name in ipairs(names) do
        if not code.found[name] then return 'code not found: ' .. name .. ' (' .. (code.missing[name] or '?') .. ')' end
    end
    for _, name in ipairs(values or {}) do
        if V[name] == nil then return 'value missing: ' .. name end
    end
end

local function finish_resolution()
    V = code.values
    local missing = code:missing_list()
    local why = need(REQUIRED, {'context', 'chat', 'local_peer', 'ring_first', 'ring_count', 'line_stride',
                                'line_sender'})
    if not why and V.ring_count ~= V.ring_first + 4 then why = 'the ring count does not follow its first index' end
    if not why and V.line_stride < 0x210 then why = 'the chat line is smaller than its text' end
    if why then
        note('Not available: ' .. why .. (#code.problems > 0 and ('; ' .. table.concat(code.problems, ', ')) or ''))
        write_status({'NOT AVAILABLE - ' .. why .. '; the game is unchanged', 'Better Chat ' .. M.version})
        M.retired = true
        return
    end
    if #code.problems > 0 then note('Signature problems: ' .. table.concat(code.problems, ', ')) end
    local base = native.base
    -- The sound: the UI sound function, found by its body and through the calls to it.
    local sound_why = need({'play_sound'})
    if not sound_why and V.ui_sound ~= code.found.play_sound then sound_why = 'the UI sound differs from its calls' end
    if not sound_why then fn.play_sound = ffi.cast('BetterChatSound', base + code.found.play_sound) end
    features.sound = sound_why or true
    -- The size: the chat widget inside the HUD and the widget scale setter.
    local scale_why = need({'chat_notice', 'set_scale'}, {'hud', 'chat_hud'})
    if not scale_why then fn.set_scale = ffi.cast('BetterChatSetVec', base + code.found.set_scale) end
    features.scale = scale_why or true
    -- Translation: curl.exe (found at start); showing a translation also needs the chat's add-line, which must be
    -- the function the chat ring's code is in.
    local show_why = need({'add_line'})
    if not show_why and code.found.add_line + 0x1c ~= code.found.chat_ring then
        show_why = 'the add-line is not where the chat ring is'
    end
    if not show_why then fn.add_line = ffi.cast('BetterChatAddLine', base + code.found.add_line) end
    features.show = show_why or true
    -- Paste: the chat widget's input-open byte (read from the code), and user32 for the keys, clipboard and window.
    local paste_why = need({'chat_input', 'chat_notice', 'chat_field', 'field_text', 'set_text'},
                           {'hud', 'chat_hud', 'chat_open', 'chat_field', 'field_max', 'field_widget', 'text_limit',
                            'widget_text'})
    if not paste_why and V.set_text_call ~= code.found.set_text then paste_why = 'the text setter differs from its call' end
    if not paste_why and not (V.field_update < code.found.field_text and code.found.field_text < V.field_update + 0x1000) then
        paste_why = 'the text input code is not in the text field update'
    end
    if not paste_why and not native.user32 then paste_why = 'user32 unavailable' end
    if not paste_why then fn.set_text = ffi.cast('BetterChatSetText', base + code.found.set_text) end
    features.paste = paste_why or true
    -- Translate Outbound: the chat's own send, found by its body, must be the function the chat box calls, and the
    -- call inside it that adds the line to the local chat must go to the add-line found above. Taking the text from
    -- the field needs paste's field and text setter; the translation needs curl.
    local send_why = need({'send_line', 'send_echo', 'add_line'}, {'send_fn', 'echo_call'})
    if not send_why and V.send_fn ~= code.found.send_line then send_why = 'the chat send differs from its call' end
    if not send_why and V.echo_call ~= code.found.add_line then send_why = "the chat send's add-line differs" end
    if not send_why and not (code.found.send_line < code.found.send_echo
                             and code.found.send_echo < code.found.send_line + 0x400) then
        send_why = 'the add-line call is not in the chat send'
    end
    if not send_why then fn.send = ffi.cast('BetterChatSend', base + code.found.send_line) end
    features.send = send_why or true
    if features.send ~= true then
        features.outbound = features.send
    elseif features.paste ~= true then
        features.outbound = "the chat's field: " .. features.paste
    else
        features.outbound = features.translate
    end
    M.ready = true
    if #code.moved > 0 then note('Moved code found: ' .. table.concat(code.moved, ', ')) end
    if #missing > 0 then note('Optional code not found: ' .. table.concat(missing, ', ')) end
    local list = {}
    for _, name in ipairs({'sound', 'scale', 'translate', 'show', 'paste', 'outbound'}) do
        list[#list + 1] = name .. ' ' .. (features[name] == true and 'ready' or ('off (' .. features[name] .. ')'))
    end
    local sounds = {}
    for _, sound in ipairs(SOUNDS) do
        local label = sound.key:sub(8)
        if sound.id then
            sounds[#sounds + 1] = string.format('%s 0x%08x', label, sound.id)
        else
            sounds[#sounds + 1] = string.format('%s %s', label,
                code.found[sound.sig] and string.format('0x%08x/0x%08x', V[sound.ship], V[sound.mission]) or 'missing')
        end
    end
    note(string.format('Ready: chat = context + 0x%x, ring at +0x%x (stride 0x%x, sender +0x%x); %s; sounds: %s',
                       V.chat, V.ring_first, V.line_stride, V.line_sender, table.concat(list, ', '),
                       table.concat(sounds, ', ')))
    write_status({'OK - watching the chat; ' .. table.concat(list, ', '), 'Better Chat ' .. M.version})
end

