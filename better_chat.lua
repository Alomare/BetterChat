local layout = {scale_base = nil, scaled = false, logged = false}

local function near(a, b) return math.abs(a - b) < 1e-4 end

local function apply_scale()
    local hud = pointer(read(native.base + V.hud, 8))
    if not hud then return end
    local widget = hud + V.chat_hud
    local sx, sy = vec_values(read(widget + 0x14, 8))
    -- A widget not laid out yet has scale 0: wait for it.
    if not sx or sx <= 0 or sy <= 0 then return end
    if not layout.logged then
        layout.logged = true
        note(string.format('Chat widget 0x%x: scale (%.3f, %.3f)', widget, sx, sy))
    end
    if not layout.scaled then layout.scale_base = {sx, sy} end
    local want = options.scale / 100
    local wx, wy = layout.scale_base[1] * want, layout.scale_base[2] * want
    if (layout.scaled or options.scale ~= 100) and not (near(sx, wx) and near(sy, wy)) then
        fn.set_scale(widget, ffi.new('BetterChatVec2', wx, wy))
        layout.scaled = options.scale ~= 100
        note(string.format('Chat scale (%.3f, %.3f) -> (%.3f, %.3f)', sx, sy, wx, wy))
    end
end

