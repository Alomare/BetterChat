-- Frame step

local function start()
    M.started = true
    local ok, why = init_native()
    if not ok then
        write_status({'NOT AVAILABLE - ' .. why .. '; the game is unchanged', 'Better Chat ' .. M.version})
        note('Native access unavailable: ' .. why)
        M.retired = true
        return
    end
    init_clock()
    -- The game's Text Language, for this mod's texts and every other mod's (bingus_text's shared registry).
    local tag, game_code = T.observe(read, native.base)
    note('Text language: ' .. tostring(T.language()) .. ' (game setting ' .. tostring(game_code or 'unreadable')
         .. ', tag ' .. tostring(tag) .. ')')
    local curl_ok, curl_why = find_curl()
    features.translate = curl_ok or curl_why
    note('Translation: ' .. (curl_ok and ('curl at ' .. translate.curl) or ('off, ' .. curl_why)))
    if curl_ok and SERVICES[options.service].id == 'custom' then load_service() end
    translate.region, translate.display = windows_languages()
    note(string.format('Windows: regional format %s, display language %s (Automatic: %s)', tostring(translate.region),
                       tostring(translate.display), tostring(google_code(translate.region) or google_code(translate.display))))
    code = sigscan.new(SIGS, read, native.base)
    local all, reason = code:start()
    if all == nil then
        write_status({'NOT AVAILABLE - ' .. reason .. '; the game is unchanged', 'Better Chat ' .. M.version})
        M.retired = true
    elseif all then
        finish_resolution()
    else
        note('Searching game.dll for moved code (game updated?)')
    end
end

local function timed(part, f)
    local t0 = perf.now and perf.now()
    f()
    if t0 then perf[part] = perf[part] + (perf.now() - t0) * 1000 end
end

local function frame(dt)
    M.frames = M.frames + 1
    clock = clock + (tonumber(dt) or 0)
    if not menu_state.menu then connect_options() end
    if not M.started then start(); return end
    if not M.ready then
        if code.scan and code:step() then finish_resolution() end
        return
    end
    if clock - last_check >= CHECK_EVERY then
        last_check = clock
        timed('chat', watch_chat)
    end
    if features.paste == true then
        if clock - paste.checked >= PASTE_CHECK_EVERY then timed('paste', check_input) end
        if paste.open then
            timed('paste', paste_step)
            if options.outbound and features.outbound == true then timed('outbound', outbound_step) end
        end
    end
    if features.translate == true then
        timed('translate', pump)
        if #translate.show > 0 or #translate.send > 0 then timed('show', deliver) end
    end
    if features.scale == true and (scale_dirty or M.frames % SCALE_EVERY == 0) then
        scale_dirty = false
        timed('scale', apply_scale)
    end
end

-- An update slower than SLOW_UPDATE is logged with its parts (each part includes the sound, curl start and log
-- writes it made; "other" is the rest: start-up, the code search, connecting to Mod Options Menu).
local function report_slow(ms)
    perf.slow = perf.slow + 1
    if perf.slow > SLOW_LOG_MAX then return end
    local other = ms - perf.chat - perf.paste - perf.outbound - perf.translate - perf.show - perf.scale
    note(string.format('Slow update: %.1f ms (chat %.1f, paste %.1f, outbound %.1f, translate %.1f, show %.1f, '
                       .. 'scale %.1f, other %.1f; inside them: sound %.1f, curl start %.1f, log %.1f in %d lines)%s',
                       ms, perf.chat, perf.paste, perf.outbound, perf.translate, perf.show, perf.scale, other,
                       perf.sound, perf.spawn, perf.log, perf.log_lines,
                       perf.slow == SLOW_LOG_MAX and '; no more slow updates logged' or ''))
end

local original_update = rawget(_G, 'update')
update = function(dt, ...)
    if not M.retired then
        local t0 = perf.now and perf.now()
        perf.chat, perf.paste, perf.outbound, perf.translate, perf.show, perf.scale = 0, 0, 0, 0, 0, 0
        perf.sound, perf.spawn, perf.log, perf.log_lines = 0, 0, 0, 0
        local ok, err = xpcall(frame, debug.traceback, dt)
        if t0 then
            local ms = (perf.now() - t0) * 1000
            if ms > SLOW_UPDATE then report_slow(ms) end
        end
        if not ok then
            M.errors = M.errors + 1
            note('Error: ' .. tostring(err))
            if M.errors >= 5 then
                M.retired = true
                write_status({'STOPPED - repeated errors (see BetterChat.log)', 'Better Chat ' .. M.version})
            end
        end
    end
    if type(original_update) == 'function' then return original_update(dt, ...) end
end

