            typedef struct { float x, y; } BetterChatVec2;
            typedef void (*BetterChatSound)(uint64_t unused, uint32_t id);
            typedef uint32_t (*BetterChatAudioId)(uint32_t id);
            typedef uint64_t (*BetterChatMakeSource)(uint64_t wwise_world);
            typedef uint32_t (*BetterChatPost)(uint64_t wwise_world, uint32_t event, uint64_t source, uint64_t unused);
            typedef void (*BetterChatSetVec)(uint64_t widget, BetterChatVec2 value);
            void *better_chat_GetCurrentProcess(void) __asm__("GetCurrentProcess");
            void *better_chat_GetModuleHandleA(const char *name) __asm__("GetModuleHandleA");
            int better_chat_ReadProcessMemory(void *process, const void *address, void *buffer, size_t size,
                                              size_t *done) __asm__("ReadProcessMemory");
        ]])
    end
    local ok, k32 = pcall(ffi.load, 'kernel32')
    if not ok then return false, 'kernel32 unavailable' end
    native.k32, native.process = k32, k32.better_chat_GetCurrentProcess()
    local game = k32.better_chat_GetModuleHandleA('game.dll')
    if game == nil then return false, 'game.dll not loaded' end
    native.base = tonumber(ffi.cast('uint64_t', game))
    return true
end

local function read(address, size)
    local buf, got = ffi.new('uint8_t[?]', size), ffi.new('size_t[1]')
    if native.k32.better_chat_ReadProcessMemory(native.process, ffi.cast('const void *', address), buf, size, got) == 0
       or tonumber(got[0]) ~= size then
        return nil
    end
    return ffi.string(buf, size)
end

local function u32(blob, offset)
    offset = offset or 0
    if not blob or #blob < offset + 4 then return nil end
    local v = ffi.new('uint32_t[1]')
    ffi.copy(v, blob:sub(offset + 1, offset + 4), 4)
    return tonumber(v[0])
end

local function read32(address) return u32(read(address, 4)) end

local function pointer(blob)
    if not blob or #blob ~= 8 then return nil end
    local v = ffi.new('uint64_t[1]')
    ffi.copy(v, blob, 8)
    local a = tonumber(v[0])
    if a < 0x10000 or a >= 0x800000000000 then return nil end
    return a
end

local function hex(blob)
    if not blob then return 'unreadable' end
    return (blob:reverse():gsub('.', function(c) return string.format('%02x', c:byte()) end))
end

-- Two floats from their 8 bytes.
local function vec_values(blob)
    if not blob or #blob ~= 8 then return nil end
    local v = ffi.new('float[2]')
    ffi.copy(v, blob, 8)
    return tonumber(v[0]), tonumber(v[1])
end

