-- Frame step

local function start()
    M.started = true
    local ok, why = init_native()
    if not ok then
        write_status({'NOT AVAILABLE - ' .. why .. '; the game is unchanged', 'Better Chat ' .. M.version})
        note('Native access unavailable: ' .. why)
        M.retired = true
        return
    end
    -- The game's Text Language, for this mod's texts and every other mod's (bingus_text's shared registry).
    local tag, game_code = T.observe(read, native.base)
    note('Text language: ' .. tostring(T.language()) .. ' (game setting ' .. tostring(game_code or 'unreadable')
         .. ', tag ' .. tostring(tag) .. ')')
    code = sigscan.new(SIGS, read, native.base)
    local all, reason = code:start()
    if all == nil then
        write_status({'NOT AVAILABLE - ' .. reason .. '; the game is unchanged', 'Better Chat ' .. M.version})
        M.retired = true
    elseif all then
        finish_resolution()
    else
        note('Searching game.dll for moved code (game updated?)')
    end
end

local function frame(dt)
    M.frames = M.frames + 1
    clock = clock + (tonumber(dt) or 0)
    if not menu_state.menu then connect_options() end
    if not M.started then start(); return end
    if not M.ready then
        if code.scan and code:step() then finish_resolution() end
        return
    end
    if clock - last_check >= CHECK_EVERY then
        last_check = clock
        watch_chat()
    end
    if features.scale == true and (scale_dirty or M.frames % SCALE_EVERY == 0) then
        scale_dirty = false
        apply_scale()
    end
end

local original_update = rawget(_G, 'update')
update = function(dt, ...)
    if not M.retired then
        local ok, err = xpcall(frame, debug.traceback, dt)
        if not ok then
            M.errors = M.errors + 1
            note('Error: ' .. tostring(err))
            if M.errors >= 5 then
                M.retired = true
                write_status({'STOPPED - repeated errors (see BetterChat.log)', 'Better Chat ' .. M.version})
            end
        end
    end
    if type(original_update) == 'function' then return original_update(dt, ...) end
end

note('Better Chat ' .. M.version .. ' loaded')
M._test = {values = function() return V end, features = function() return features end,
           options = function() return options end}  -- offline checks
return M
