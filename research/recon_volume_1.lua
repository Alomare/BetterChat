local V = {}      -- values read from the matched code (offsets; globals and functions as rvas)
local fn = {}     -- the game's functions that were found
local features = {}  -- feature -> true, or the reason it is off

local function need(names, values)
    for _, name in ipairs(names) do
        if not code.found[name] then return 'code not found: ' .. name .. ' (' .. (code.missing[name] or '?') .. ')' end
    end
    for _, name in ipairs(values or {}) do
        if V[name] == nil then return 'value missing: ' .. name end
    end
end

local function finish_resolution()
    V = code.values
    local missing = code:missing_list()
    local why = need(REQUIRED, {'context', 'chat', 'local_peer', 'ring_first', 'ring_count', 'line_stride',
                                'line_sender'})
    if not why and V.ring_count ~= V.ring_first + 4 then why = 'the ring count does not follow its first index' end
    if not why and V.line_stride < 0x210 then why = 'the chat line is smaller than its text' end
    if why then
        note('Not available: ' .. why .. (#code.problems > 0 and ('; ' .. table.concat(code.problems, ', ')) or ''))
        write_status({'NOT AVAILABLE - ' .. why .. '; the game is unchanged', 'Better Chat ' .. M.version})
        M.retired = true
        return
    end
    if #code.problems > 0 then note('Signature problems: ' .. table.concat(code.problems, ', ')) end
    local base = native.base
    -- The sound: the UI sound function, found by its body and through the calls to it.
    local sound_why = need({'play_sound'})
    if not sound_why and V.ui_sound ~= code.found.play_sound then sound_why = 'the UI sound differs from its calls' end
    if not sound_why then fn.play_sound = ffi.cast('BetterChatSound', base + code.found.play_sound) end
    features.sound = sound_why or true
    -- The volume: the inside of that sound function (its engine calls and the sound id lookup) and the engine's
    -- Lua API for a source's level.
    local volume_why = sound_why or need({'ui_post'}, {'engine', 'make_source', 'ui_world', 'post_event', 'audio_id',
                                                       'game_state'})
    if not volume_why and (code.found.ui_post < code.found.play_sound or code.found.ui_post > code.found.play_sound + 0x40) then
        volume_why = 'the sound source code is not inside the UI sound'
    end
    if not volume_why then
        local S = rawget(_G, 'stingray')
        local wwise, wwise_world = type(S) == 'table' and S.Wwise, type(S) == 'table' and S.WwiseWorld
        if not (wwise and wwise.wwise_world and wwise_world and wwise_world.set_dry_environment_for_source
                and S.Application and S.Application.main_world) then
            volume_why = 'the engine has no source level function'
        end
    end
    if not volume_why then fn.audio_id = ffi.cast('BetterChatAudioId', base + V.audio_id) end
    features.volume = volume_why or true
    -- The size: the chat widget inside the HUD and the widget scale setter.
    local scale_why = need({'chat_notice', 'set_scale'}, {'hud', 'chat_hud'})
    if not scale_why then fn.set_scale = ffi.cast('BetterChatSetVec', base + code.found.set_scale) end
    features.scale = scale_why or true
    M.ready = true
    if #code.moved > 0 then note('Moved code found: ' .. table.concat(code.moved, ', ')) end
    if #missing > 0 then note('Optional code not found: ' .. table.concat(missing, ', ')) end
    local list = {}
    for _, name in ipairs({'sound', 'volume', 'scale'}) do
        list[#list + 1] = name .. ' ' .. (features[name] == true and 'ready' or ('off (' .. features[name] .. ')'))
    end
    local sounds = {}
    for i = 2, #SOUNDS do
        local sound = SOUNDS[i]
        sounds[#sounds + 1] = string.format('%s %s', sound.key:sub(8),
            code.found[sound.sig] and string.format('0x%08x/0x%08x', V[sound.ship], V[sound.mission]) or 'missing')
    end
    note(string.format('Ready: chat = context + 0x%x, ring at +0x%x (stride 0x%x, sender +0x%x); %s; sounds: %s',
                       V.chat, V.ring_first, V.line_stride, V.line_sender, table.concat(list, ', '),
                       table.concat(sounds, ', ')))
    write_status({'OK - watching the chat; ' .. table.concat(list, ', '), 'Better Chat ' .. M.version})
end

